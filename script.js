function formatCurrency(value) {
  return value.toFixed(2).replace('.', ',');
}

function converterProdutoParaCarrinho(produto) {
  return {
    id: produto.id,
    name: produto.nome,
    price: `R$ ${formatCurrency(produto.preco)}`,
    image: produto.imagem
  };
}

function formatPrice(price) {
  return Number(
    price
      .replace('R$ ', '')
      .replace(',', '.')
  );
}

function updateCart() {
  cartItems.innerHTML = '';

  if (cart.length === 0) {
    cartItems.innerHTML = `
      <p class="empty-cart">
        Seu carrinho está vazio. Adicione produtos para finalizar sua compra.
      </p>
    `;

    cartCount.textContent = 0;
    cartTotal.textContent = 'Total: R$ 0,00';
    return;
  }

  let total = 0;
  let totalItems = 0;

  cart.forEach((item, index) => {
    const subtotal = formatPrice(item.price) * item.quantity;

    total += subtotal;
    totalItems += item.quantity;

    const cartItem = document.createElement('div');
    cartItem.classList.add('cart-item');

    cartItem.innerHTML = `
      <h4>${item.name}</h4>
      <p>Preço: ${item.price}</p>

      <div class="cart-actions">
        <button onclick="decreaseQuantity(${index})">-</button>
        <span>${item.quantity}</span>
        <button onclick="increaseQuantity(${index})">+</button>
        <button class="remove-btn" onclick="removeFromCart(${index})">Remover</button>
      </div>

      <strong>Subtotal: R$ ${formatCurrency(subtotal)}</strong>
    `;

    cartItems.appendChild(cartItem);
  });

  cartCount.textContent = totalItems;
  cartTotal.textContent = `Total: R$ ${formatCurrency(total)}`;
}

function addToCart(product) {
  const productExists = cart.find((item) => item.id === product.id);

  if (productExists) {
    productExists.quantity += 1;
  } else {
    cart.push({
      ...product,
      quantity: 1
    });
  }

  updateCart();
  alert(`${product.name} adicionado ao carrinho!`);
}

function increaseQuantity(index) {
  cart[index].quantity += 1;
  updateCart();
}

function decreaseQuantity(index) {
  if (cart[index].quantity > 1) {
    cart[index].quantity -= 1;
  } else {
    cart.splice(index, 1);
  }

  updateCart();
}

function removeFromCart(index) {
  cart.splice(index, 1);
  updateCart();
}

function finalizarCompra() {
  if (cart.length === 0) {
    alert('Seu carrinho está vazio. Adicione produtos para finalizar a compra.');
    return;
  }

  let mensagem = '🛒 *Pedido Valentina Artesanatos*%0A%0A';
  let total = 0;

  cart.forEach((item) => {
    const subtotal = formatPrice(item.price) * item.quantity;
    total += subtotal;

    mensagem += `🧶 Produto: ${item.name}%0A`;
    mensagem += `Código do produto: ${item.id}%0A`;
    mensagem += `Quantidade: ${item.quantity}%0A`;
    mensagem += `Subtotal: R$ ${formatCurrency(subtotal)}%0A%0A`;
  });

  mensagem += `💰 *Total: R$ ${formatCurrency(total)}*%0A%0A`;
  mensagem += 'Olá! Gostaria de finalizar este pedido.';

  const telefone = '5521972856635';
  const url = `https://wa.me/${telefone}?text=${mensagem}`;

  window.open(url, '_blank');
}

function renderizarProdutosEmDestaque() {
  productGrid.innerHTML = '';

  produtos.slice(0, 5).forEach((produto) => {
    const product = converterProdutoParaCarrinho(produto);

    const card = document.createElement('article');
    card.classList.add('product-card');

    card.innerHTML = `
      <button class="favorite">♡</button>
      <img src="${produto.imagem}" alt="${produto.nome}">
      <div class="product-info">
        <h3>${produto.nome}</h3>
        <strong>R$ ${formatCurrency(produto.preco)}</strong>
        <button class="add-cart">Comprar</button>
      </div>
    `;

    card.querySelector('.add-cart').addEventListener('click', () => {
      addToCart(product);
    });

    card.querySelector('.favorite').addEventListener('click', (event) => {
      event.target.textContent = event.target.textContent === '♡' ? '♥' : '♡';
    });

    productGrid.appendChild(card);
  });
}

function abrirModalCategoria(categoria) {
  const produtosFiltrados = produtos.filter(
    (produto) => produto.categoria === categoria
  );

  tituloCategoria.innerText = ` ${formatarCategoria(categoria)}`;

  if (produtosFiltrados.length === 0) {
    produtosCategoria.innerHTML = `
      <p class="empty-cart">
        Nenhum produto encontrado nessa categoria.
      </p>
    `;
  } else {
    produtosCategoria.innerHTML = produtosFiltrados
      .map((produto) => {
        return `
          <div class="produto-modal">
            <img src="${produto.imagem}" alt="${produto.nome}">
            <h3>${produto.nome}</h3>
            <p>A partir de R$ ${formatCurrency(produto.preco)}</p>
            <button onclick="adicionarProdutoCategoriaAoCarrinho(${produto.id})">
              Adicionar ao carrinho
            </button>
          </div>
        `;
      })
      .join('');
  }

  modalCategoria.classList.add('ativo');
}

function adicionarProdutoCategoriaAoCarrinho(id) {
  const produtoSelecionado = produtos.find((produto) => produto.id === id);

  if (!produtoSelecionado) {
    alert('Produto não encontrado.');
    return;
  }

  const produtoFormatado = converterProdutoParaCarrinho(produtoSelecionado);
  addToCart(produtoFormatado);
}

function formatarCategoria(categoria) {
  const nomes = {
    arcos:'Arcos',
    brincos:'Brincos',
    canetas:'Canetas',
    chaveiros:'Chaveiros',
    colares:'Colares',
    junino:'Junino',
    laços:'Laços',
    presentes:'Presentes',
    pulseiras:'Pulseiras',
  };

  return nomes[categoria] || categoria;
}

